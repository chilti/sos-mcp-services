#!/usr/bin/env python3
"""
SOM Trajectory Mapping CLI (som_trajectory_cli.py)
--------------------------------------------------
State-Space Trajectory Mapping with Kohonen Self-Organizing Maps (SOM),
Centered Moving Average (CMA) smoothing, and continuous Cubic Spline interpolation
(Jiménez-Andrade, Arencibia-Jorge & Carrillo-Calvet, 2025).

Features:
- Reads entity longitudinal series (.parquet, .csv, .json) from the Workspace
  (e.g., ./matrices/series_cma_som.parquet generated by tlachia_metrics_cli.py annual-series --level ... --cma-window 3).
- Enforces KnoMap's ergonomic rule of maximum 5 simultaneous entities in visualization
  (--entities or --top-entities <= 5), while training the SOM over the full universe of peers.
- Allows selecting any subset of indicators (--indicator-cols) or using all numeric
  indicator columns without truncation.
- Detects Temporal Inflection Points (inter-cluster topological jumps or maximum velocity) and
  Community Maturation Phases (% Top 10% >= 10.0%).
- Generates the interactive dashboard with trajectory controls (./reports/som_trajectories.html)
  and the analytical manifest (./reports/som_trajectories.json).
"""

