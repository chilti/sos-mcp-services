"""
SOM Methodological Expert CLI (som_pipeline_cli.py)
---------------------------------------------------
Workspace-First neurocomputational pipeline to train Kohonen Self-Organizing Maps (SOM)
on multidimensional [N x D] matrices generated by tlachia-metrics-engine,
tlachia-metrics-handler, or scientometrics-incites-expert.

Features:
- Directly reads .parquet, .csv, or .json files from the Workspace (e.g., ./matrices/indicadores_som.parquet).
- Allows selecting any subset of dimensions (--indicator-cols) or using all available
  numeric indicator columns without truncation.
- Z-score / MinMax / Robust normalization prior to training.
- Automatic SVD spectral grid sizing (Small SOM 5*sqrt(N) or Big SOM 10*N) or explicit (--rows, --cols).
- Vesanto hierarchical meta-clustering with automatic k selection via Silhouette Score (or --clusters k).
- Automatic diagnosis of Comparable Peers (same BMU or adjacent neurons) and detection of the
  FWCI vs. Average Percentile Paradox.
- Persistence in ./reports/som_state.json and interactive rendering in ./reports/som_dashboard.html.
"""

