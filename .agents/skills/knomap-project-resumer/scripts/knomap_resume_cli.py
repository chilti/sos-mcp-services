def _match_matrix_for_run(ws: Path, som_path: Path, run_idx: int) -> Tuple[Optional[Path], Optional[Path]]:
    """Find normalized & original matrices matching a som_state file inside workspace/matrices."""
    m_dir = ws / "matrices"
    if not m_dir.exists():
        return None, None

    stem = som_path.stem
    # Pattern from extract-workspace: som_state_run_02_slug -> som_matrix_run_02_slug
    m = re.match(r"som_state(_run_\d+_.*)", stem)
    if m:
        suffix = m.group(1)
        norm_cand = next((p for p in [m_dir / f"som_matrix{suffix}.csv", m_dir / f"som_matrix{suffix}.parquet"] if p.exists()), None)
        orig_cand = next((p for p in [m_dir / f"som_matrix{suffix}_original.csv"] if p.exists()), None)
        if norm_cand or orig_cand:
            return norm_cand, orig_cand

    if stem == "som_state" or run_idx == 0:
        for base in ("som_matrix", "indicadores_som"):
            norm_cand = next((p for p in [m_dir / f"{base}.csv", m_dir / f"{base}.parquet"] if p.exists()), None)
            orig_cand = next((p for p in [m_dir / f"{base}_original.csv"] if p.exists()), None)
            if norm_cand or orig_cand:
                return norm_cand, orig_cand
    return None, None


