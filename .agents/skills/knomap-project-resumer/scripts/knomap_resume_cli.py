def extract_unit_cache(cache_obj: Dict[str, Any], prefix: str, matrices_dir: Path) -> Dict[str, List[str]]:
    outputs: Dict[str, List[str]] = {}
    for unit_name, unit_data in cache_obj.items():
        if not isinstance(unit_data, dict):
            continue
        slug = safe_slug(unit_name)
        unit_files: List[str] = []

        profile = unit_data.get("profile")
        if isinstance(profile, list) and profile:
            unit_files.extend(save_tabular_records(
                profile,
                matrices_dir / f"{prefix}_{slug}.csv",
                matrices_dir / f"{prefix}_{slug}.parquet",
            ))

        profile_5y = unit_data.get("profile_5years")
        if isinstance(profile_5y, list) and profile_5y:
            unit_files.extend(save_tabular_records(
                profile_5y,
                matrices_dir / f"{prefix}_{slug}_5years.csv",
            ))

        for extra_key in ("time_series", "longitudinal", "profile_evolution"):
            if unit_data.get(extra_key):
                unit_files.append(write_json(matrices_dir / f"{prefix}_{slug}_{extra_key}.json", unit_data[extra_key]))

        if unit_files:
            outputs[unit_name] = unit_files
    return outputs


