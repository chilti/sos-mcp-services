#!/usr/bin/env python3
"""
Standalone CLI for knomap-project-resumer.
Opens portable KnoMap project files (.knoMap v2.1 JSON, server .json.gz, or .knomap v2.0),
inspects all research modules and AI assistant history without flooding stdout,
extracts standardized workspace artifacts (./matrices, ./networks, ./reports),
and optionally updates a .knoMap project with new findings generated by CLI agents.
"""

