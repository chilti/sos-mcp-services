def main():
    parser = argparse.ArgumentParser(description="Bibliometric Search Strategist - Query Synthesizer CLI (Aligned with GLOBAL / ISSI)")
    parser.add_argument("--action", choices=["validate", "transpile", "format"], required=True, help="Action to execute (validate, transpile, or format)")
    parser.add_argument("--query", type=str, help="Boolean search string to validate or format")
    parser.add_argument("--config", type=str, help="JSON/YAML file with conceptual block definitions")
    parser.add_argument("--output", type=str, default="./search_output", help="Directory to save generated artifacts")
    parser.add_argument(
        "--lang",
        type=str,
        choices=["en", "es"],
        default="en",
        help="Output language for labels/messages (en or es)"
    )

    args = parser.parse_args()
    lang = getattr(args, "lang", "en") or "en"
    msg = MESSAGES.get(lang, MESSAGES["en"])

    if args.action == "validate":
        if not args.query:
            print(msg["req_query_validate"], file=sys.stderr)
            sys.exit(1)
        res = QueryValidator.validate(args.query, lang=lang)
        print(msg["val_header"])
        status_str = msg["valid_yes"] if res["is_valid"] else msg["valid_no"]
        print(msg["val_status"].format(status=status_str))
        print(msg["val_stats"].format(chars=res["character_count"], tokens=res["approx_tokens"]))
        if res["errors"]:
            print(msg["val_errors"])
            for e in res["errors"]:
                print(f"  ❌ {e}")
        if res["warnings"]:
            print(msg["val_warnings"])
            for w in res["warnings"]:
                print(f"  ⚠️ {w}")
        if not res["errors"] and not res["warnings"]:
            print(msg["val_clean"])
        sys.exit(0 if res["is_valid"] else 1)

    elif args.action == "transpile":
        if not args.config:
            print(msg["req_config_transpile"], file=sys.stderr)
            sys.exit(1)
        if not os.path.exists(args.config):
            print(msg["config_not_found"].format(path=args.config), file=sys.stderr)
            sys.exit(1)

        with open(args.config, "r", encoding="utf-8") as f:
            spec = json.load(f)

        transpiler = QueryTranspiler(spec, lang=lang)
        os.makedirs(args.output, exist_ok=True)

        wos_q = transpiler.to_wos()
        scopus_q = transpiler.to_scopus()
        pubmed_q = transpiler.to_pubmed()
        ch_sql = transpiler.to_clickhouse_sql()
        global_md = transpiler.generate_global_template()

        with open(os.path.join(args.output, "wos_query.txt"), "w", encoding="utf-8") as f:
            f.write(wos_q)
        with open(os.path.join(args.output, "scopus_query.txt"), "w", encoding="utf-8") as f:
            f.write(scopus_q)
        with open(os.path.join(args.output, "pubmed_query.txt"), "w", encoding="utf-8") as f:
            f.write(pubmed_q)
        with open(os.path.join(args.output, "clickhouse_query.sql"), "w", encoding="utf-8") as f:
            f.write(ch_sql)
        with open(os.path.join(args.output, "global_audit.md"), "w", encoding="utf-8") as f:
            f.write(global_md)

        print(msg["transpile_done"].format(output=args.output))
