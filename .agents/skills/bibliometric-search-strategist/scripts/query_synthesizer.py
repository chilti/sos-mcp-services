class QueryValidator:
    """Syntactic and best-practice validator (PRESS 2015 / GLOBAL) for Boolean queries."""

    @staticmethod
    def check_parentheses(query: str, lang: str = "en") -> List[str]:
        msg = MESSAGES.get(lang, MESSAGES["en"])
        errors = []
        stack = []
        for i, char in enumerate(query):
            if char == '(':
                stack.append(i)
            elif char == ')':
                if not stack:
                    errors.append(msg["orphan_close_paren"].format(pos=i))
                else:
                    stack.pop()
        if stack:
            for pos in stack:
                errors.append(msg["unclosed_open_paren"].format(pos=pos))
        return errors

    @staticmethod
    def check_quotes(query: str, lang: str = "en") -> List[str]:
        msg = MESSAGES.get(lang, MESSAGES["en"])
        errors = []
        quote_count = query.count('"')
        if quote_count % 2 != 0:
            errors.append(msg["unbalanced_quotes"].format(count=quote_count))
        return errors

    @staticmethod
    def check_lowercase_operators(query: str, lang: str = "en") -> List[str]:
        msg = MESSAGES.get(lang, MESSAGES["en"])
        warnings = []
        parts = re.split(r'("[^"]*")', query)
        for i, part in enumerate(parts):
            if i % 2 == 0:  # Outside quotes
                for match in re.finditer(r'\b(and|or|not)\b', part):
                    warnings.append(
                        msg["lowercase_op"].format(op=match.group(0), upper=match.group(0).upper())
                    )
        return warnings

    @staticmethod
    def check_dangerous_wildcards(query: str, lang: str = "en") -> List[str]:
        msg = MESSAGES.get(lang, MESSAGES["en"])
        warnings = []
        for match in re.finditer(r'\b([a-zA-Z]{1,3})\*', query):
            warnings.append(
                msg["short_wildcard"].format(full=match.group(0), stem=match.group(1))
            )
        return warnings

    @staticmethod
    def check_empty_clauses(query: str, lang: str = "en") -> List[str]:
        msg = MESSAGES.get(lang, MESSAGES["en"])
        errors = []
        patterns = [
            (r'\b(AND|OR|NOT)\s+(AND|OR)\b', msg["consecutive_ops"]),
            (r'\(\s*(AND|OR)\b', msg["leading_op_paren"]),
            (r'\b(AND|OR|NOT)\s*\)', msg["trailing_op_paren"]),
            (r'\(\s*\)', msg["empty_parens"])
        ]
        for pat, err_msg in patterns:
            if re.search(pat, query, re.IGNORECASE):
                errors.append(err_msg)
        return errors

    @classmethod
    def validate(cls, query: str, lang: str = "en") -> Dict[str, Any]:
        paren_errs = cls.check_parentheses(query, lang=lang)
        quote_errs = cls.check_quotes(query, lang=lang)
        empty_errs = cls.check_empty_clauses(query, lang=lang)
        op_warns = cls.check_lowercase_operators(query, lang=lang)
        wild_warns = cls.check_dangerous_wildcards(query, lang=lang)

        is_valid = len(paren_errs) == 0 and len(quote_errs) == 0 and len(empty_errs) == 0

        return {
            "is_valid": is_valid,
            "errors": paren_errs + quote_errs + empty_errs,
            "warnings": op_warns + wild_warns,
            "character_count": len(query),
            "approx_tokens": len(query.split())
        }


class QueryTranspiler:
    """Transpiles a structured block definition into WoS, Scopus, PubMed, and ClickHouse."""

    def __init__(self, spec: Dict[str, Any], lang: str = "en"):
        self.spec = spec
        self.lang = lang
        msg = MESSAGES.get(lang, MESSAGES["en"])
        # Supports 'blocks' (preferred in scientometrics) and 'facets' (backward compatibility)
        self.blocks = spec.get("blocks", spec.get("facets", []))
        self.facets = self.blocks
        self.filters = spec.get("filters", {})
        self.title = spec.get("project_title", msg["default_title"])

    def to_wos(self) -> str:
        block_clauses = []
        for block in self.blocks:
            terms = block.get("terms", [])
            wos_terms = [f'"{t}"' if " " in t and not t.startswith('"') else t for t in terms]
            clause = " OR ".join(wos_terms)
            block_clauses.append(f"TS=({clause})")

        query = "\n  AND ".join(block_clauses)

        # Filters
        filter_parts = []
        y_start = self.filters.get("year_start")
        y_end = self.filters.get("year_end")
        if y_start and y_end:
            filter_parts.append(f"PY=({y_start}-{y_end})")
        elif y_start:
            filter_parts.append(f"PY>=({y_start})")

        doc_types = self.filters.get("doc_types", [])
        if doc_types:
            dt_map = {"article": "Article", "review": "Review"}
            dt_vals = [dt_map.get(d.lower(), d.capitalize()) for d in doc_types]
            filter_parts.append(f"DT=({' OR '.join(dt_vals)})")

        if filter_parts:
            query += "\n  AND " + "\n  AND ".join(filter_parts)

        return query

    def to_scopus(self) -> str:
        block_clauses = []
        for block in self.blocks:
            terms = block.get("terms", [])
            scopus_terms = [f'"{t}"' if " " in t and not t.startswith('"') else t for t in terms]
            clause = " OR ".join(scopus_terms)
            block_clauses.append(f"TITLE-ABS-KEY({clause})")

        query = "\n  AND ".join(block_clauses)

        filter_parts = []
        y_start = self.filters.get("year_start")
        y_end = self.filters.get("year_end")
        if y_start and y_end:
            filter_parts.append(f"PUBYEAR > {y_start - 1} AND PUBYEAR < {y_end + 1}")
        elif y_start:
            filter_parts.append(f"PUBYEAR > {y_start - 1}")

        doc_types = self.filters.get("doc_types", [])
        if doc_types:
            dt_map = {"article": "ar", "review": "re", "conference": "cp"}
            dt_vals = [f"DOCTYPE({dt_map.get(d.lower(), d)})" for d in doc_types]
            filter_parts.append(f"({' OR '.join(dt_vals)})")

        if filter_parts:
            query += "\n  AND " + "\n  AND ".join(filter_parts)

        return query

    def to_pubmed(self) -> str:
        block_clauses = []
        for block in self.blocks:
            terms = block.get("terms", [])
            mesh_terms = block.get("mesh", [])
            tiab_terms = [f'"{t}"[tiab]' if " " in t and not t.startswith('"') else f'{t}[tiab]' for t in terms]
            mesh_clauses = [f'"{m}"[mesh]' for m in mesh_terms]
            all_block_terms = tiab_terms + mesh_clauses
            clause = " OR ".join(all_block_terms)
            block_clauses.append(f"({clause})")

        query = "\n  AND ".join(block_clauses)

        filter_parts = []
        y_start = self.filters.get("year_start")
        y_end = self.filters.get("year_end")
        if y_start and y_end:
            filter_parts.append(f"{y_start}:{y_end}[dp]")

        doc_types = self.filters.get("doc_types", [])
        if doc_types:
            dt_map = {"article": "journal article", "review": "review"}
            dt_vals = [f'"{dt_map.get(d.lower(), d)}"[pt]' for d in doc_types]
            filter_parts.append(f"({' OR '.join(dt_vals)})")

        if filter_parts:
            query += "\n  AND " + "\n  AND ".join(filter_parts)

        return query

    def to_clickhouse_sql(self, table_override: str = None) -> str:
        """Generate optimized SQL for rag.works_flat (global) or rag.works_academic_all (Mexico) with ZERO JOINs."""
        msg = MESSAGES.get(self.lang, MESSAGES["en"])
        where_conditions = []

        for block in self.blocks:
            terms = block.get("terms", [])
            topics = block.get("topics", [])
            block_subs = []

            for t in terms:
                clean_term = t.replace("'", "\\'").replace("*", "")
                block_subs.append(f"positionCaseInsensitiveUTF8(title, '{clean_term}') > 0")
                block_subs.append(f"arrayExists(x -> positionCaseInsensitiveUTF8(x, '{clean_term}') > 0, keywords)")

            for top in topics:
                clean_top = top.replace("'", "\\'")
                block_subs.append(f"positionCaseInsensitiveUTF8(topic, '{clean_top}') > 0")

            clause = "(\n      " + "\n      OR ".join(block_subs) + "\n    )"
            where_conditions.append(clause)

        # Filters
        y_start = self.filters.get("year_start")
        y_end = self.filters.get("year_end")
        if y_start and y_end:
            where_conditions.append(f"(publication_year >= {y_start} AND publication_year <= {y_end})")
        elif y_start:
            where_conditions.append(f"publication_year >= {y_start}")

        doc_types = self.filters.get("doc_types", [])
        if doc_types:
            dt_str = ", ".join(f"'{d.lower()}'" for d in doc_types)
            where_conditions.append(f"type IN ({dt_str})")

        countries = self.filters.get("countries", [])
        is_mexico_only = (len(countries) == 1 and countries[0] in ("Mexico", "MX")) or self.filters.get("scope") == "mexico"
        if "Mexico" in countries or "MX" in countries:
            where_conditions.append("(country_code = 'MX' OR has(all_country_codes, 'MX'))")

        oa_status = self.filters.get("oa_status")
        if oa_status:
            where_conditions.append(f"oa_status = '{oa_status.lower()}'")

        target_table = table_override or self.filters.get("table") or ("rag.works_academic_all" if is_mexico_only else "rag.works_flat")
        ref_expr = "referenced_works" if "works_flat" in target_table else "JSONExtract(raw_data, 'referenced_works', 'Array(String)') AS referenced_works"

        sql = msg["sql_comment_1"]
        sql += msg["sql_comment_2"].format(table=target_table)
        sql += "SELECT\n"
        sql += "    id,\n"
        sql += "    doi,\n"
        sql += "    title,\n"
        sql += "    publication_year,\n"
        sql += "    publication_year AS year,\n"
        sql += "    type,\n"
        sql += "    type AS doc_type,\n"
        sql += "    language,\n"
        sql += "    oa_status,\n"
        sql += "    is_oa,\n"
        sql += "    cited_by_count,\n"
        sql += "    cited_by_count AS citations,\n"
        sql += "    fwci,\n"
        sql += "    percentile,\n"
        sql += "    is_top_10,\n"
        sql += "    is_top_1,\n"
        sql += "    apc_paid_usd,\n"
        sql += "    apc_list_usd,\n"
        sql += "    is_doaj_indexed,\n"
        sql += "    has_repository_fulltext,\n"
        sql += "    source_id AS source_title,\n"
        sql += "    source_type,\n"
        sql += "    author_names,\n"
        sql += "    arrayStringConcat(author_names, '; ') AS authors,\n"
        sql += "    institution_names,\n"
        sql += "    arrayStringConcat(institution_names, '; ') AS affiliations,\n"
        sql += "    institution_rors,\n"
        sql += "    all_country_codes,\n"
        sql += "    arrayStringConcat(all_country_codes, '; ') AS country_codes,\n"
        sql += "    country_code,\n"
        sql += "    topic,\n"
        sql += "    subfield,\n"
        sql += "    field,\n"
        sql += "    domain,\n"
        sql += "    keywords,\n"
        sql += "    arrayStringConcat(keywords, '; ') AS keywords_author,\n"
        sql += "    sdgs,\n"
        sql += f"    {ref_expr}\n"
        sql += f"FROM {target_table}\n"
        sql += "WHERE\n  " + "\n  AND ".join(where_conditions) + "\n"
        sql += "ORDER BY cited_by_count DESC\n"
        sql += "LIMIT 5000\n"

        return sql

